- **Item 7 is future PRs only.** No self-heal, no back-fill of existing PR descriptions.

## Interlocks, and the order they force

The three files are numbered 1–12 but the *work* order is not the file order:

1. **The iOS test failure** — in flight, finish it.
2. **CI cheap wins** (\`ios-ci-cheap-wins-prompt.md\`) — same file you are already in, additive,
   independent of everything else. Fold it in while you are there.
3. **Item 1 (dead chip taps)** — it blocks the flow. Items 2, 3 and 4 cannot be exercised end to
   end until a chip tap works, so nothing about onboarding is verifiable before this lands.
4. **Item 8 (mobile-web reload flash)** — early, because every remaining item is verified at
   phone width and the flash makes that miserable. It also touches \`TripWorkspace\`'s layout
   branch, which is the same tree items 4 and 9 render inside.
5. **Items 2, 3, 4 + 9 (onboarding)** — read item 4 and item 9 together before touching either;
   9 amends 4.
6. **Item 5 (delete the paste row)** BEFORE **item 10 (navigation links)**. Both edit
   \`src/components/StopsSection.tsx\`. Doing 10 first means making the paste-row region work and
   then deleting it, and risks 10's "make the whole row a link" change getting entangled with
   affordances item 5 removes.
7. **Item 11 (units)** after item 10 — both sweep \`Itinerary.tsx\` and \`StopsSection.tsx\`, and
   item 11's fix at \`formatKmDual\`/\`Distance\` changes what item 10's rows render. One pass over
   those two files instead of three.
8. **Item 6 (vanishing fuel stop)** — the only item whose cause I do not know. Give it the time
   that needs and its own commit; do not ship a guess bundled with the rest.
9. **Items 7, 12 and 13** — independent, whenever. Item 13 (per-user paywall enforcement) is
   unblocked by nothing and blocks nothing; it is what lets the paywall be tested while the global
   switch stays off for the web demo.

