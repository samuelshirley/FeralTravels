## Ground rules — these apply to every item

1. **Reproduce before you fix.** Every cause written in these files came from *reading* the
   source, not from watching it fail. Confirm each one in the environment where it actually
   happens and say where I am wrong. If something cannot be reproduced, say so plainly instead
   of offering a confident theory.
2. **Playwright MCP first** for anything browser-shaped — reproduce in a real browser before
   theorising or writing diagnostic scripts. It is registered in \`.mcp.json\`. If it is not
   loaded in your session, Claude in Chrome is the fallback, not an excuse to skip the step.
3. **Reliability is worth the time and the money.** Do not trim coverage, depth or fidelity to
   save CI minutes, API spend or PR wall-clock. If cost is genuinely relevant, measure it and
   give me the number — do not pre-emptively narrow a testing proposal on cost grounds.
4. **Structural guards over detection tests.** Prefer the change that makes a class of bug
   impossible over a test that notices one instance of it. Where a file says a shape has drifted
   before, that is the shape to make impossible.
5. **Mutation-check every new test.** Reintroduce the exact bug, watch the test go red, restore.
   Name which tests you checked this way. A test that has never failed has proven nothing.
6. **Never re-type file content from tool output** when editing — output can be truncated. Edit
   in place with a command or a short read-modify-write script.
7. **Commit, do not push.** Scoped commits, one per item where they separate cleanly, once
   \`tsc --noEmit\` and \`npm run test\` pass. Do not push, do not open a PR, do not merge — I do
   that.
8. **Documentation moves with the code.** If a change makes a comment, \`CLAUDE.md\` or
   \`docs/design/nocturne-reskin.md\` wrong, fix it in the same commit. Several of these items
   exist *because* that did not happen last time.

