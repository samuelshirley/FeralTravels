#!/usr/bin/env bash
#
# Assemble the whole open bug campaign into ONE brief and hand it to Claude Code.
#
# ── Why this exists ────────────────────────────────────────────────────────
#
# The work is written down across three prompt files under docs/bugs/, and they
# are not independent: item 9 amends item 4, item 5 deletes code that item 10
# then edits, and item 11 changes a formatter that items 10 and 4 both render
# through. Handing them over one file at a time invites exactly the failure the
# separate files were meant to avoid — an agent fixing item 10 against a
# StopsSection that item 5 was supposed to have already gutted, or building the
# receipts UI that item 9 cancels.
#
# So this emits a single ordered brief: the ground rules, the decisions already
# made (so they are not re-litigated), the interlocks and the order they force,
# the documentation that is currently WRONG and must not be trusted, then the
# three prompt files in full.
#
# ── Usage ──────────────────────────────────────────────────────────────────
#
#   scripts/handoff-bug-campaign.sh              assemble, copy to clipboard, print the path
#   scripts/handoff-bug-campaign.sh --launch     assemble, then start `claude` with it
#   scripts/handoff-bug-campaign.sh --print      assemble, write it to stdout (for piping)
#
# The brief lands in .handoff/ at the repo root, which this script adds to
# .gitignore itself if it is not already there. It is regenerated every run, so
# editing it is pointless — edit the docs/bugs/ files and re-run.

set -euo pipefail

# Resolve the repo root from THIS script's location rather than $PWD, so the
# script works from any directory and does not depend on being run from the
# repo root.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

MODE="copy"
case "${1:-}" in
  --launch) MODE="launch" ;;
  --print)  MODE="print" ;;
  "")       MODE="copy" ;;
  *)
    echo "Unknown argument: $1" >&2
    echo "Usage: $0 [--launch|--print]" >&2
    exit 2
    ;;
esac

# The prompt files, in the order they belong in the brief.
PROMPTS=(
  "docs/bugs/onboarding-fix-prompt.md"
  "docs/bugs/mobile-web-nav-units-prompt.md"
  "docs/bugs/paywall-per-user-testing-prompt.md"
  "docs/bugs/ios-ci-cheap-wins-prompt.md"
)

# Fail loudly and name what is missing, rather than emitting a brief with a
# silent hole in it.
missing=()
for f in "${PROMPTS[@]}"; do
  [[ -f "$f" ]] || missing+=("$f")
done
if (( ${#missing[@]} > 0 )); then
  echo "Missing prompt file(s):" >&2
  printf '  %s\n' "${missing[@]}" >&2
  exit 1
fi

OUT_DIR="$REPO_ROOT/.handoff"
OUT="$OUT_DIR/campaign-brief.md"
mkdir -p "$OUT_DIR"

# Keep the generated brief out of git without anyone having to remember to.
if ! grep -qx '.handoff/' .gitignore 2>/dev/null; then
  printf '\n# Generated by scripts/handoff-bug-campaign.sh\n.handoff/\n' >> .gitignore
  echo "Added .handoff/ to .gitignore"
fi

# Real repository state, read at generation time. An agent picking this up
# needs to know which branch it is on and whether the tree is dirty — those
# are the two facts most likely to make its first command wrong.
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
HEAD_SHA="$(git rev-parse --short HEAD)"
if [[ -n "$(git status --porcelain)" ]]; then
  TREE_STATE="DIRTY — uncommitted changes present (see \`git status\` before you start)"
else
  TREE_STATE="clean"
fi
GENERATED_AT="$(date '+%Y-%m-%d %H:%M %Z')"

{
cat <<HEADER
# Feral Travels — open bug campaign, items 1–13 plus CI

Generated $GENERATED_AT by \`scripts/handoff-bug-campaign.sh\`. Do not edit this file; edit the
sources under \`docs/bugs/\` and re-run the script.

Branch: \`$BRANCH\` at \`$HEAD_SHA\` · working tree: $TREE_STATE

You are already working on the current \`iOS e2e (simulator)\` failure. **Finish that first.**
Everything below is queued behind it. Nothing here is urgent enough to justify leaving a red
test job half-diagnosed.

