# The prompt files, in full, with headers that survive concatenation.
i=0
for f in "${PROMPTS[@]}"; do
  i=$((i + 1))
  printf '\n\n<!-- ===================== SOURCE %d/%d: %s ===================== -->\n\n' \
    "$i" "${#PROMPTS[@]}" "$f"
  cat "$f"
  printf '\n\n---\n'
done
} > "$OUT"

LINES="$(wc -l < "$OUT" | tr -d ' ')"
BYTES="$(wc -c < "$OUT" | tr -d ' ')"

case "$MODE" in
  print)
    cat "$OUT"
    ;;
  launch)
    if ! command -v claude >/dev/null 2>&1; then
      echo "No \`claude\` on PATH — cannot launch." >&2
      echo "The brief is written to: $OUT" >&2
      exit 1
    fi
    echo "Brief: $OUT ($LINES lines, $BYTES bytes). Starting claude…"
    exec claude "$(cat "$OUT")"
    ;;
  copy)
    echo "Brief written: $OUT ($LINES lines, $BYTES bytes)"
    if command -v pbcopy >/dev/null 2>&1; then
      pbcopy < "$OUT"
      echo "Copied to the clipboard — paste it into the session that is on the iOS failure."
    else
      echo "No pbcopy on this machine; paste it from the file above."
    fi
    echo
    echo "Or hand it over directly:  $0 --launch"
    ;;
esac
