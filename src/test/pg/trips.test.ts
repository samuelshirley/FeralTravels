/**
 * Trips and everything that hangs off one, through the real repos against a
 * real Postgres: what is written comes back exactly, and deleting a trip (or
 * its owner) takes the dependent rows with it, as the FKs in schema.ts say.
 */

beforeEach(resetDb);

const GEOMETRY = {
  type: 'LineString' as const,
  coordinates: [
    [-3.7038, 40.4168],
    [-0.3763, 39.4699],
  ] as [number, number][],
};

async function tripWithLeg() {
  const user = await seedUser();
  const trip = await createTrip({ userId: user.id, name: 'Spain loop', startDate: '2026-03-01' });
  const legId = await addLeg({
    tripId: trip.id,
    title: 'ignored, derived from the endpoints',
    startName: 'Madrid',
    endName: 'Valencia',
    startLat: 40.4168,
    startLng: -3.7038,
    endLat: 39.4699,
    endLng: -0.3763,
    distanceKm: 356.4,
    driveTimeMinutes: 215,
    geometry: GEOMETRY,
  });
  return { user, trip, legId };
}

describe('trips', () => {
  it('a date column comes back as the same calendar day, in any process timezone', async () => {
    const before = process.env.TZ;
    // Ahead of UTC, so a date turned into a local-midnight Date and back
    // would land on the day before.
    process.env.TZ = 'Pacific/Auckland';
    try {
      const user = await seedUser();
      const trip = await createTrip({
        userId: user.id,
        name: 'Date check',
        startDate: '2026-03-01',
        endDate: '2026-03-09',
      });
      expect(trip.start_date_parsed).toBe('2026-03-01');
      expect(trip.end_date_parsed).toBe('2026-03-09');
      const full = await getTripFull(trip.id);
      expect(full?.start_date_parsed).toBe('2026-03-01');
      expect(full?.end_date_parsed).toBe('2026-03-09');
      const [stored] = await rawQuery<{ d: string }>(
        `select start_date_parsed::text as d from trips where id = $1`,
        [trip.id],
      );
      expect(stored.d).toBe('2026-03-01');
    } finally {
      if (before === undefined) delete process.env.TZ;
      else process.env.TZ = before;
    }
  });

  it('the enum column takes its default and reads back as the value written', async () => {
    const { db } = await testDb();
    const user = await seedUser();
    const trip = await createTrip({ userId: user.id, name: 'Enum check' });
    expect(trip.trip_status).toBe('draft');
    await db.update(trips).set({ tripStatus: 'paused' }).where(eq(trips.id, trip.id));
    expect((await getTripFull(trip.id))?.trip_status).toBe('paused');
    const err = await pgError(
      db.execute(`update trips set trip_status = 'cancelled' where id = '${trip.id}'` as never),
    );
    expect(err.code).toBe('22P02'); // invalid_text_representation: not in the enum
  });

  it('trip_name_ci_key is generated by Postgres as lower(trim(name))', async () => {
    const user = await seedUser();
    const trip = await createTrip({ userId: user.id, name: '  Big Sur RUN ' });
    const [row] = await rawQuery<{ k: string; generated: string }>(
      `select t.trip_name_ci_key as k, c.is_generated as generated
         from trips t, information_schema.columns c
        where t.id = $1 and c.table_name = 'trips' and c.column_name = 'trip_name_ci_key'`,
      [trip.id],
    );
    expect(row).toEqual({ k: 'big sur run', generated: 'ALWAYS' });
  });

  it('the unique index refuses a second trip whose name differs only in case and spaces', async () => {
    const { db } = await testDb();
    const user = await seedUser();
    await createTrip({ userId: user.id, name: 'Coast Road' });
    // Straight insert: past the repo's friendly pre-check, which is not the
    // backstop. The index is.
    const err = await pgError(
      db.insert(trips).values({ userId: user.id, name: ' coast road  ' }),
    );
    expect(err.code).toBe('23505');
    expect(err.constraint).toBe('trips_user_name_unique_idx');
    // Per user, not global.
    const other = await seedUser();
    await expect(createTrip({ userId: other.id, name: 'COAST ROAD' })).resolves.toBeTruthy();
  });

  it('createTrip refuses a taken name with a 409 before it reaches the index', async () => {
    const user = await seedUser();
    await createTrip({ userId: user.id, name: 'Alps' });
    await expect(createTrip({ userId: user.id, name: ' ALPS ' })).rejects.toMatchObject({
      status: 409,
    });
  });

  it('timestamptz: the position time is the same instant whatever the session zone', async () => {
    const { client } = await testDb();
    const user = await seedUser();
    const trip = await createTrip({ userId: user.id, name: 'Clock' });
    await updateTripPosition(trip.id, 46.948, 7.4474, 'Bern');
    const utc = (await getTripFull(trip.id))!;
    await client.exec(`set time zone 'Asia/Kolkata'`);
    try {
      const kolkata = (await getTripFull(trip.id))!;
      expect(kolkata.position_updated_at).toBe(utc.position_updated_at);
      expect(kolkata.last_known_place).toBe('Bern');
      expect(kolkata.last_known_lat).toBe(46.948);
    } finally {
      await client.exec(`set time zone 'UTC'`);
    }
  });

  it('listTripsForUser returns the trip with its day count and distance', async () => {
    const { user, trip } = await tripWithLeg();
    const list = await listTripsForUser(user.id);
    expect(list.map((t) => t.id)).toEqual([trip.id]);
    expect(list[0].day_count).toBe(1);
    expect(list[0].total_distance_km).toBe(356);
  });

  it('declared fuel state round-trips', async () => {
    const { trip, legId } = await tripWithLeg();
    await setDeclaredFuelState(trip.id, { remainingRangeKm: 152.5, legId });
    const full = (await getTripFull(trip.id))!;
    expect(full.declared_range_km).toBe(152.5);
    expect(full.declared_range_leg_id).toBe(legId);
    expect(Date.parse(full.declared_range_at!)).not.toBeNaN();
  });
});

describe('legs', () => {
  it('geometry jsonb and the derived title come back as written', async () => {
    const { trip, legId } = await tripWithLeg();
    const full = (await getTripFull(trip.id))!;
    const leg = full.legs.find((l) => l.id === legId)!;
    expect(leg.geometry).toEqual(GEOMETRY);
    expect(leg.title).toBe('Madrid → Valencia');
    expect(leg.distance_km).toBe(356.4);
    expect(leg.drive_time_minutes).toBe(215);
    const [stored] = await rawQuery<{ t: string }>(
      `select jsonb_typeof(geometry->'coordinates') as t from legs where id = $1`,
      [legId],
    );
    expect(stored.t).toBe('array'); // a jsonb array, not a JSON string
  });
});

describe('routes and route_links', () => {
  it('a route and its links round-trip, and links sort under their route', async () => {
    const { legId } = await tripWithLeg();
    const route = await addRoute({
      leg_id: legId,
      label: 'Coastal',
      description: 'Via the N-332',
      distance_km: 380.2,
      surface: 'paved',
      end_lat: 39.47,
      end_lng: -0.376,
      end_name: 'Valencia',
      end_source: 'manual',
      end_source_url: 'https://maps.example/valencia',
      drive_time_minutes: 240,
      links: [{ label: 'Wikiloc', url: 'https://wikiloc.example/1', type: 'gpx' }],
    });
    await addRouteLink({ route_id: route.id, label: 'Blog', url: 'https://blog.example/n332' });
    const back = (await getRoute(route.id))!;
    expect(back).toMatchObject({
      leg_id: legId,
      sort_order: 0,
      label: 'Coastal',
      description: 'Via the N-332',
      distance_km: 380.2,
      surface: 'paved',
      status: 'option',
      end_name: 'Valencia',
      end_source: 'manual',
      end_source_url: 'https://maps.example/valencia',
      drive_time_minutes: 240,
    });
    expect(back.links.map((l) => [l.label, l.url, l.type]).sort()).toEqual([
      ['Blog', 'https://blog.example/n332', 'other'],
      ['Wikiloc', 'https://wikiloc.example/1', 'gpx'],
    ]);
    const second = await addRoute({ leg_id: legId, label: 'Inland' });
    expect(second.sort_order).toBe(1);
    expect((await getRoutesForLeg(legId)).map((r) => r.label)).toEqual(['Coastal', 'Inland']);
  });
});

describe('stops', () => {
  it('a user stop round-trips through add and update', async () => {
    const { legId } = await tripWithLeg();
    const stop = await addStop({
      leg_id: legId,
      stop_type: 'other',
      name: 'Cuenca',
      lat: 40.0704,
      lng: -2.1374,
      distance_from_start_km: 167.25,
      notes: 'Hanging houses',
      source: 'user',
      place_id: 'ChIJ-cuenca',
      google_maps_uri: 'https://maps.google.com/?cid=1',
    });
    expect(stop).toMatchObject({ sort_order: 0, status: 'option', distance_from_start_km: 167.25 });
    const updated = await updateStop(stop.id, { status: 'selected', notes: null });
    expect(updated).toMatchObject({ status: 'selected', notes: null, place_id: 'ChIJ-cuenca' });
    expect((await getStopsForLeg(legId)).map((s) => s.id)).toEqual([stop.id]);
  });

  it("a fuel stop's jsonb reason and alternatives come back exactly as Finn stored them", async () => {
    const { db } = await testDb();
    const { legId } = await tripWithLeg();
    const alternatives = [
      { name: 'Repsol Tarancón', lat: 40.01, lng: -3.0, place_id: 'p1', distance_km: 81.5 },
      { name: 'Cepsa', lat: 40.02, lng: -2.9, place_id: null, distance_km: 90 },
    ];
    const forcedReason = { kind: 'next_fuel_far' as const, gap_km: 212 };
    // Finn's writer (server/fuel.ts) needs Google; this is the row it writes.
    const [row] = await db
      .insert(stops)
      .values({
        legId,
        stopType: 'fuel',
        name: 'Shell Motilla',
        source: 'finn',
        alternatives,
        forcedReason,
      })
      .returning();
    const back = (await getStop(row.id))!;
    expect(back.alternatives).toEqual(alternatives);
    expect(back.forced_reason).toEqual(forcedReason);
  });
});

