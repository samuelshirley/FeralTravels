describe('pois and links', () => {
  it('cloneTrip copies a trip with its legs, stops (jsonb intact), pois and links', async () => {
    const { db } = await testDb();
    const { user, trip, legId } = await tripWithLeg();
    const forcedReason = { kind: 'next_day_fuel_far' as const, gap_km: 301 };
    await db.insert(stops).values({ legId, stopType: 'fuel', name: 'BP', forcedReason });
    await db.insert(links).values({ legId, label: 'Campsite', url: 'https://camp.example' });
    const lastVerified = new Date('2026-02-01T12:00:00Z');
    await db.insert(pois).values({
      tripId: trip.id,
      legId,
      source: 'osm',
      name: 'Viewpoint',
      lat: 39.9,
      lng: -1.2,
      rating: 4.5,
      lastVerified,
    });
    const copyId = await cloneTrip(trip.id, user.id);
    const copy = (await getTripFull(copyId))!;
    expect(copy.name).toBe('Spain loop (copy)');
    expect(copy.start_date_parsed).toBe('2026-03-01');
    expect(copy.legs).toHaveLength(1);
    const copyLeg = copy.legs[0];
    expect(copyLeg.id).not.toBe(legId);
    expect(copyLeg.geometry).toEqual(GEOMETRY);
    const copyStops = await getStopsForLeg(copyLeg.id);
    expect(copyStops.map((s) => s.forced_reason)).toEqual([forcedReason]);
    expect(copyLeg.links.map((l) => [l.label, l.url])).toEqual([['Campsite', 'https://camp.example']]);
    expect((await getPoisForTrip(trip.id))[0]).toMatchObject({
      leg_id: legId,
      source: 'osm',
      name: 'Viewpoint',
      rating: 4.5,
      last_verified: lastVerified.toISOString(),
    });
    const copyPois = await getPoisForTrip(copyId);
    expect(copyPois).toHaveLength(1);
    // last_verified is not asserted on the copy: cloneTrip does not carry it.
    expect(copyPois[0]).toMatchObject({ leg_id: copyLeg.id, name: 'Viewpoint', rating: 4.5 });
  });
});

describe('cascades', () => {
  async function counts(tripId: string) {
    const [row] = await rawQuery<Record<string, number>>(
      `select
         (select count(*)::int from legs where trip_id = $1) as legs,
         (select count(*)::int from stops s join legs l on l.id = s.leg_id where l.trip_id = $1) as stops,
         (select count(*)::int from routes) as routes,
         (select count(*)::int from route_links) as route_links,
         (select count(*)::int from tasks where trip_id = $1) as tasks,
         (select count(*)::int from pois where trip_id = $1) as pois,
         (select count(*)::int from links) as links,
         (select count(*)::int from chat_history where trip_id = $1) as chat`,
      [tripId],
    );
    return row;
  }

  async function fullTrip() {
    const { db } = await testDb();
    const { user, trip, legId } = await tripWithLeg();
    const route = await addRoute({ leg_id: legId, label: 'A' });
    await addRouteLink({ route_id: route.id, label: 'x', url: 'https://x.example' });
    await addStop({ leg_id: legId, stop_type: 'other', name: 'Stop' });
    await addTask({ trip_id: trip.id, leg_id: legId, title: 'Task' });
    await db.insert(pois).values({ tripId: trip.id, legId, source: 'osm', name: 'P', lat: 1, lng: 1 });
    await db.insert(links).values({ legId, label: 'L', url: 'https://l.example' });
    return { user, trip };
  }

  it('deleting a trip takes its legs, routes, route links, stops, tasks, pois and links', async () => {
    const { trip } = await fullTrip();
    expect(await counts(trip.id)).toEqual({
      legs: 1, stops: 1, routes: 1, route_links: 1, tasks: 1, pois: 1, links: 1, chat: 0,
    });
    await deleteTrip(trip.id);
    expect(await counts(trip.id)).toEqual({
      legs: 0, stops: 0, routes: 0, route_links: 0, tasks: 0, pois: 0, links: 0, chat: 0,
    });
  });

  it('deleting a user takes their trips and everything under them', async () => {
    const { db } = await testDb();
    const { user, trip } = await fullTrip();
    await db.delete(users).where(eq(users.id, user.id));
    expect(await getTripFull(trip.id)).toBeNull();
    expect((await counts(trip.id)).legs).toBe(0);
    expect((await rawQuery(`select 1 from routes`)).length).toBe(0);
  });

  it('deleting a leg takes its stops but leaves the trip', async () => {
    const { db } = await testDb();
    const { trip } = await fullTrip();
    await db.delete(legs).where(eq(legs.tripId, trip.id));
    expect(await counts(trip.id)).toMatchObject({ legs: 0, stops: 0, routes: 0, tasks: 0 });
    expect(await getTripFull(trip.id)).not.toBeNull();
  });
});
